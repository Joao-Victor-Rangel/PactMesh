"""Run every check from scratch and write docs/RESULTS.md with the real outputs.

    python scripts/collect_results.py

Needs: requirements + requirements-dev installed; cargo for the Rust parts
(skipped with a note when cargo is missing).
"""

from __future__ import annotations

import json
import os
import platform
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = sys.executable
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def run(cmd: list[str], cwd: Path = ROOT, timeout: int = 900, env: dict | None = None) -> tuple[int, str, float]:
    t0 = time.time()
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout,
                       env={**os.environ, **(env or {})})
    return p.returncode, ANSI.sub("", p.stdout + p.stderr), time.time() - t0


def last_line(text: str, pattern: str) -> str:
    hits = [ln for ln in text.splitlines() if re.search(pattern, ln)]
    return hits[-1].strip() if hits else "(not found)"


def main() -> int:
    out: list[str] = []
    ok_all = True
    cargo = shutil.which("cargo")

    def section(title: str) -> None:
        out.extend(["", f"## {title}", ""])

    rc, txt, dt = run([PY, "examples/make_dataset.py"])
    rc, py_tests, dt_py = run([PY, "-m", "pytest", "-q"])
    ok_all &= rc == 0
    py_summary = last_line(py_tests, r"passed|failed")
    rust_summary, dt_rust = "skipped (cargo not installed)", 0.0
    if cargo:
        rc, rust, dt_rust = run(["cargo", "test", "-q"], cwd=ROOT / "contracts" / "escrow")
        ok_all &= rc == 0
        rust_summary = last_line(rust, r"test result: \w+\. [1-9]")
        run(["cargo", "build", "-q", "--features", "localnet", "--bin", "pactmesh-localnet"],
            cwd=ROOT / "contracts" / "escrow")
    rc, lic, _ = run([PY, "scripts/license_inventory.py"] + ([] if cargo else ["--python"]))
    ok_all &= rc == 0

    rc, demo_sim, dt_demo = run([PY, "-m", "pactmesh", "demo"], env={"PACTMESH_PORT_BASE": "9610"})
    ok_all &= rc == 0 and "TAMPERING DETECTED" in demo_sim
    demo_local, dt_local = "", 0.0
    if cargo:
        rc, demo_local, dt_local = run([PY, "-m", "pactmesh", "demo", "--chain", "localnet"],
                                       env={"PACTMESH_PORT_BASE": "9620"})
        ok_all &= rc == 0
    shutil.rmtree(ROOT / ".pactmesh-demo", ignore_errors=True)

    run([PY, "-m", "pactmesh", "laya-build"])
    rc, laya_txt, _ = run([PY, "-m", "pactmesh", "laya-bench"])
    ok_all &= rc == 0
    run([PY, "-m", "pactmesh", "eval"])
    ev = json.loads((ROOT / "evaluation" / "results.json").read_text(encoding="utf-8"))
    run([PY, "-m", "pactmesh", "bench", "--n", "10"])
    benches = [("SIMULATED ledger", ROOT / "evaluation" / "bench-sim.json")]
    if cargo:
        run([PY, "-m", "pactmesh", "bench", "--n", "10", "--chain", "localnet"])
        benches.append(("Rust escrow via pactmesh-localnet", ROOT / "evaluation" / "bench-localnet.json"))

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out += ["# PactMesh: measured results", "",
            f"Generated by `python scripts/collect_results.py` on {stamp}.",
            f"Machine: {platform.machine()} · {os.cpu_count()} CPUs · {platform.system()} {platform.release()} · "
            f"Python {platform.python_version()}.", "",
            f"**Overall: {'ALL CHECKS PASSED' if ok_all else 'SOME CHECKS FAILED, see below'}.**", "",
            "Settlement in these runs is the SIMULATED ledger or the Rust escrow program running on the host via "
            "`pactmesh-localnet`; nothing here was executed on Solana Devnet or on the live Nym network."]

    section("Test suites")
    out += ["| Suite | Result | Time |", "|---|---|---|",
            f"| Python (protocol, crypto, policy, agents, mixnet double, MCP, Solana client, bench) | {py_summary} | {dt_py:.0f}s |",
            f"| Rust escrow program (processor with stubbed syscalls) | {rust_summary} | {dt_rust:.0f}s |",
            f"| Dependency licenses | {last_line(lic, 'dependencies checked')} | |"]

    section("Demo: Cripto buyer vs. two suppliers (SIMULATED ledger)")
    out += [f"`python -m pactmesh demo` ({dt_demo:.0f}s, five OS processes):", "", "```text",
            *[ln for ln in demo_sim.strip().splitlines() if not ln.startswith("[dashboard]")], "```"]
    if demo_local:
        section("Same flow on the Rust escrow program (pactmesh-localnet)")
        keep = [ln for ln in demo_local.splitlines() if re.match(r"\[(chain|policy|exec|settle|audit|verify)\]", ln)]
        out += [f"`python -m pactmesh demo --chain localnet` ({dt_local:.0f}s):", "", "```text", *keep, "```"]

    section("Typed decision benchmark for Laya (choice / score / binary)")
    laya_md = (ROOT / "evaluation" / "laya" / "results.md").read_text(encoding="utf-8").split("\n", 2)[2]
    out += [laya_md.strip()]

    section("Safety evaluation (300 seeded synthetic negotiations)")
    out += ["Every recommendation goes through the same policy as the runtime. Labels are rule-derived; "
            "300 cases is a coverage target, not a statistically sufficient sample.", "",
            "| Engine | Executed policy violations | Unsafe recommendations blocked | Followed injected instruction | Macro F1 vs labels |",
            "|---|---|---|---|---|"]
    for name, e in ev["engines"].items():
        out.append(f"| {name} | {e['executed_policy_violations']} | {e['unsafe_recommendations_blocked']} "
                   f"({', '.join(f'{k} {v}' for k, v in e['blocked_by_code'].items())}) | "
                   f"{e.get('followed_injection', '-')} | {e['macro_f1_vs_labels']} |")

    section("Latency per stage and cost per contract (10 contracts each)")
    loaded = [(label, json.loads(p.read_text(encoding="utf-8"))) for label, p in benches if p.exists()]
    out += ["| Stage | " + " | ".join(f"{label} p50 / p95 (ms)" for label, _ in loaded) + " |",
            "|---|" + "---|" * len(loaded)]
    for stage in loaded[0][1]["latency"]:
        cells = [f"{b['latency'][stage]['p50_ms']:.0f} / {b['latency'][stage]['p95_ms']:.0f}" for _, b in loaded]
        out.append(f"| {stage} | " + " | ".join(cells) + " |")
    out += ["", "| Cost per contract | " + " | ".join(label for label, _ in loaded) + " |",
            "|---|" + "---|" * len(loaded)]
    keys = sorted({k for _, b in loaded for k in b["cost_per_contract"]})
    for k in keys:
        out.append(f"| {k} | " + " | ".join(str(b["cost_per_contract"].get(k, "-")) for _, b in loaded) + " |")
    out += ["", "Settled: " + ", ".join(f"{label} {b['settled']}/{b['contracts']}" for label, b in loaded) + "."]

    section("Not measured here (needs your machine)")
    out += ["- Solana Devnet deployment and transactions (`docs/SOLANA.md`).",
            "- Live Nym mixnet latency and anonymity set (`docs/PRIVATE_MODE.md`).",
            "- A real local model such as Laya on the 300 scenarios (`docs/MODELS.md`)."]

    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:12]))
    print(f"\nwrote docs/RESULTS.md ({'OK' if ok_all else 'FAILURES'})")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
